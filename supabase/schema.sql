-- ---------- Profiles ----------
-- NOTE: target_cgpa is NUMERIC(4,2). NUMERIC(3,2) tops out at 9.99 and
-- would reject the upper bound 10.00 that the CHECK constraint allows.
CREATE TABLE public.profiles (
    id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL PRIMARY KEY,
    full_name TEXT NOT NULL,
    academic_level TEXT NOT NULL DEFAULT 'foundational'
        CHECK (academic_level IN ('foundational', 'diploma', 'bsc', 'bs')),
    target_cgpa NUMERIC(4,2) DEFAULT 8.00 CHECK (target_cgpa >= 4.00 AND target_cgpa <= 10.00),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ---------- Student courses ----------
-- term_id stores the academic level key the course belongs to
-- ('foundational' | 'diploma' | 'bsc' | 'bs'); the dashboard filters on it.
CREATE TABLE public.student_courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
    course_name TEXT NOT NULL,
    term_id TEXT NOT NULL,
    current_gaa NUMERIC(5,2) DEFAULT 0.00 CHECK (current_gaa >= 0 AND current_gaa <= 100),
    -- Official ledger: NULL = not taken / not released yet.
    quiz_1 INT CHECK (quiz_1 BETWEEN 0 AND 100),
    quiz_2 INT CHECK (quiz_2 BETWEEN 0 AND 100),
    is_q2_skipped BOOLEAN DEFAULT FALSE,
    final_score INT CHECK (final_score BETWEEN 0 AND 100),
    target_grade_letter VARCHAR(2) DEFAULT 'S' CHECK (target_grade_letter IN ('S','A','B','C','D')),
    -- Weekly GA scores by week (JSON array of numbers / nulls) and how many best ones count toward GAA.
    weekly_scores JSONB NOT NULL DEFAULT '[]'::jsonb,
    gaa_best_k INT NOT NULL DEFAULT 6 CHECK (gaa_best_k BETWEEN 1 AND 12),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    UNIQUE (user_id, course_name, term_id)
);

CREATE INDEX student_courses_user_idx ON public.student_courses (user_id, term_id);

-- ---------- updated_at maintenance ----------
CREATE OR REPLACE FUNCTION public.touch_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = TIMEZONE('utc'::text, NOW());
    RETURN NEW;
END;
$$;

CREATE TRIGGER profiles_touch_updated_at
    BEFORE UPDATE ON public.profiles
    FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

-- ---------- Row Level Security ----------
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.student_courses ENABLE ROW LEVEL SECURITY;

CREATE POLICY "profiles_select_own" ON public.profiles
    FOR SELECT USING (auth.uid() = id);
CREATE POLICY "profiles_insert_own" ON public.profiles
    FOR INSERT WITH CHECK (auth.uid() = id);
CREATE POLICY "profiles_update_own" ON public.profiles
    FOR UPDATE USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

CREATE POLICY "courses_select_own" ON public.student_courses
    FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "courses_insert_own" ON public.student_courses
    FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "courses_update_own" ON public.student_courses
    FOR UPDATE USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "courses_delete_own" ON public.student_courses
    FOR DELETE USING (auth.uid() = user_id);

-- ---------- Automatic profile creation on sign-up ----------
-- Fires for Google OAuth and phone OTP sign-ups alike. Phone users carry no
-- name metadata, so we fall back to 'Student' (editable from the dashboard).
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO public.profiles (id, full_name)
    VALUES (
        NEW.id,
        COALESCE(
            NULLIF(NEW.raw_user_meta_data ->> 'full_name', ''),
            NULLIF(NEW.raw_user_meta_data ->> 'name', ''),
            'Student'
        )
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Backfill profiles for users that signed up before the trigger existed.
INSERT INTO public.profiles (id, full_name)
SELECT u.id, COALESCE(NULLIF(u.raw_user_meta_data ->> 'full_name', ''), NULLIF(u.raw_user_meta_data ->> 'name', ''), 'Student')
FROM auth.users u
ON CONFLICT (id) DO NOTHING;
